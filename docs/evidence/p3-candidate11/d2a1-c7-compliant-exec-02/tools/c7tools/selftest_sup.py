#!/usr/bin/env python3
"""Self-test of c7sup.py build/invoke on THROWAWAY scratch crates (never the Nexus repository). selftest_sup.py <scratch-dir>"""
import json, os, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import c7sup
from c7lib import *  # noqa

res = []
def expect(n, c, d=""):
    res.append(bool(c)); print("[%s] %s %s" % ("OK" if c else "FAILED", n, d), flush=True)

base = os.path.abspath(sys.argv[1]); os.makedirs(base)
def mk(name, lib):
    d = os.path.join(base, name); os.makedirs(os.path.join(d, "src"))
    open(os.path.join(d, "Cargo.toml"), "w").write('[package]\nname="%s"\nversion="0.1.0"\nedition="2021"\n[lib]\n' % name)
    open(os.path.join(d, "Cargo.lock"), "w").write('# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "%s"\nversion = "0.1.0"\n' % name)
    open(os.path.join(d, "rust-toolchain.toml"), "w").write('[toolchain]\nchannel = "1.94.0"\n')
    open(os.path.join(d, "src/lib.rs"), "w").write(lib)
    os.makedirs(os.path.join(d, "target"))
    return d
ok_lib = '#[cfg(test)]\nmod t {\n    #[test]\n    fn one() { assert_eq!(1, 1); }\n    #[test]\n    #[ignore]\n    fn two() {}\n}\n'
A = mk("scratcha", ok_lib)
W = mk("scratchw", ok_lib + "pub fn f() { let x = 1; }\n")
E = mk("scratche", ok_lib + "pub fn f() { let x: u32 = \"s\"; }\n")
argv = ["cargo", "test", "--locked", "--release", "--lib", "--no-run", "-j", "2"]
rc = c7sup.build(os.path.join(base, "b-ok"), A, "E-W", argv=argv, check_source=False, exe_prefix="scratcha")
d = json.load(open(os.path.join(base, "b-ok/descriptor.json")))
expect("clean build: rc 0", rc == 0, "rc %s" % rc)
expect("clean build: one executable pinned, zero warnings/errors", len(d["pinned_executables"]) == 1 and d["compiler_messages"]["warnings"] == 0 and d["compiler_messages"]["errors"] == 0, str(d["executable_lines"]))
expect("clean build: Executable line resolved to the deps scan", d["executables_found"] == [d["pinned_executables"][0]["path"]])
expect("clean build: inventory + fingerprint recorded", any("fingerprint" in f["path"] for f in d["inventory"]) and len(d["inventory"]) > 3, "%d files" % len(d["inventory"]))
expect("clean build: toolchain recorded", "rustc 1.94.0" in d["toolchain"]["rustc -vV"])
rc = c7sup.build(os.path.join(base, "b-warn"), W, "E-W", argv=argv, check_source=False, exe_prefix="scratchw")
d = json.load(open(os.path.join(base, "b-warn/descriptor.json")))
expect("warning build: warnings counted (>0)", d["compiler_messages"]["warnings"] > 0, str(d["compiler_messages"]))
rc = c7sup.build(os.path.join(base, "b-err"), E, "E-W", argv=argv, check_source=False, exe_prefix="scratche")
d = json.load(open(os.path.join(base, "b-err/descriptor.json")))
expect("error build: rc != 0, errors counted, no executable pinned", rc != 0 and d["compiler_messages"]["errors"] > 0 and not d["pinned_executables"], "rc %s" % rc)
# the build timeout: a 3 s limit around a sleeping cargo substitute
rc = c7sup.build(os.path.join(base, "b-timeout"), A, "E-W", argv=["sleep", "30"], check_source=False, limit=3, exe_prefix="scratcha")
d = json.load(open(os.path.join(base, "b-timeout/descriptor.json")))
expect("timeout: killed, flagged, not clean", rc != 0 and d["supervisor"]["timed_out"] and d["process"]["signal"] == 9 or d["process"]["exit_status"] in (124, 137), str(d["process"]))
exe = json.load(open(os.path.join(base, "b-ok/descriptor.json")))["pinned_executables"][0]
for label, args, rcwant, pat in (("list", ["--list"], 0, "2 tests"), ("list-ignored", ["--list", "--ignored"], 0, "1 test"),
                                  ("exact-one", ["t::one", "--exact", "--nocapture", "--test-threads=1"], 0, "1 passed; 0 failed; 0 ignored; 0 measured; 1 filtered out")):
    rc = c7sup.invoke(os.path.join(base, "i-" + label), A, label, exe["path"], exe["sha256"], 60, args, cwd=A)
    raw = open(os.path.join(base, "i-" + label, "raw-output.txt")).read()
    dd = json.load(open(os.path.join(base, "i-" + label, "descriptor.json")))
    expect("invoke %s" % label, rc == 0 and pat in raw and dd["process"]["exit_status"] == rcwant and dd["executable"]["sha256_after"] == exe["sha256"], repr(raw[-120:]))
rc = c7sup.invoke(os.path.join(base, "i-wrongsha"), A, "x", exe["path"], "0" * 64, 60, ["--list"], cwd=A)
expect("invoke with a wrong pinned sha is NOT STARTED", rc == 5 and not os.path.exists(os.path.join(base, "i-wrongsha/raw-output.txt")))
print("\nSELF-TEST (c7sup build/invoke) %s: %d/%d" % ("ALL OK" if all(res) else "FAILED", sum(res), len(res)))
sys.exit(0 if all(res) else 1)
