#!/usr/bin/env python3
"""Renders PROOF-PRECONDITION-MATRIX.md from the TSV and the matrix and proof-docs receipts.

Mission P3-C11-DR01-D2A1-FINAL-SOURCE-PROOF-READINESS-01. Deterministic: the final gate
re-renders it and requires the frozen file byte for byte. The TSV is authoritative; this
file is a reading aid. Usage: render_matrix.py <tsv> <matrix.json> <proof-docs.json> <out.md>
"""
import csv
import json
import sys

csv.field_size_limit(10 ** 9)
ORDER = ['IDENTICAL', 'NON_INTERFERING_CHANGE', 'CHANGED_REVIEW_REQUIRED', 'EXECUTION_PENDING',
         'OWNER_ALREADY_SATISFIED', 'NOT_ESTABLISHED']
EXPLAIN = {
    'IDENTICAL': 'every cited source item is byte-identical at C to the item the statement cites (same bytes; '
                 'the byte range may have moved, and both ranges are in the TSV)',
    'NON_INTERFERING_CHANGE': 'the statement also rests on the whole model_tests.rs blob; at C that blob keeps the cited '
                              'version as a byte prefix and only appends layers, each isolated from the text before it, '
                              'with both witness additions NON_INTERFERING (executor static finding; AD-1-R4 N leaves '
                              'the ruling to the Architect)',
    'CHANGED_REVIEW_REQUIRED': 'a cited item differs at C from the text the statement cites',
    'EXECUTION_PENDING': 'the statement needs a run, a build or a runtime guard at the exact final commit; none is made here',
    'OWNER_ALREADY_SATISFIED': 'an Owner decision, recorded at C by the adoption audit record',
    'NOT_ESTABLISHED': 'nothing here establishes it: the independent review itself, an acceptance that is not the '
                       "executor's, or a stated limit of the claim",
}


def main():
    tsv, mjson, pjson, out = sys.argv[1:5]
    rows = list(csv.DictReader(open(tsv), delimiter='\t'))
    m = json.load(open(mjson))
    p = json.load(open(pjson))
    docs = {d['key']: d for d in p['documents']}
    L = []
    w = L.append
    w('# Proof-precondition matrix')
    w('')
    w('Mission P3-C11-DR01-D2A1-FINAL-SOURCE-PROOF-READINESS-01. Generated by `tools/render_matrix.py` from')
    w('`PROOF-PRECONDITION-MATRIX.tsv` (authoritative, %d rows) and `receipts/15-matrix.json`. Candidate C is' % len(rows))
    w('`d5964ee5326c2733177307db6f507328023d361a`.')
    w('')
    w('**A static status is a statement about source identity, not about truth.** No row accepts a proof, proves a')
    w('theorem, or records a run. Only the Sole Architect rules on the proofs.')
    w('')
    w('## Proof documents cited')
    w('')
    w('| Key | Sealed document (under the evidence root `%s/`) | sha256 | Written against | Implemented at |'
      % p['evidence_root'])
    w('|---|---|---|---|---|')
    for key, impl in (('ADM-PROOF', '83816e66 (AQ)'), ('GC-PROOF', '77a146ca (SQ)'), ('EXT-PROOF', '2d83b74b (EXT)')):
        d = docs[key]
        w('| %s | `%s` | `%s` | `%s` | %s |' % (
            key, d['sealed_path'][len(p['evidence_root']) + 1:], d['sha256'],
            d['source_binding']['claimed_source_commit'][:8], impl))
    w('')
    w('Each is transported byte for byte at `8693e3a742ee4d3917cbfdb809b377bcd919d9f4` (see')
    w('PROOF-DOCUMENT-INTEGRITY.md). AD-1-R4 rows cite the adopted addendum at C. A row\'s line numbers are the')
    w("document's own, at the commit it was written against; `tools/matrix.py` resolves them to items by byte range.")
    w('')
    w('## Static statuses')
    w('')
    w('| Status | Rows | Meaning |')
    w('|---|---|---|')
    for s in ORDER:
        w('| %s | %d | %s |' % (s, m['status_counts'].get(s, 0), EXPLAIN[s]))
    w('')
    w('## By group')
    w('')
    w('| Group | ' + ' | '.join(ORDER) + ' |')
    w('|---|' + '---|' * len(ORDER))
    groups = []
    for r in rows:
        if r['group'] not in groups:
            groups.append(r['group'])
    for g in groups:
        c = m['group_status_counts'][g]
        w('| %s | %s |' % (g, ' | '.join(str(c.get(s, 0)) or '0' for s in ORDER)))
    w('')
    w('## Rows that are not IDENTICAL')
    w('')
    for s in ORDER[1:]:
        ids = [r for r in rows if r['static_status'] == s]
        if not ids:
            continue
        w('**%s** (%d)' % (s, len(ids)))
        w('')
        for r in ids:
            note = (' ' + r['note']) if r['note'] else ''
            w('- `%s` %s.%s' % (r['id'], r['statement'], note))
        w('')
    w('## All rows')
    w('')
    w('Items are listed by name; their byte ranges and sha256 at the cited commit and at C are in the TSV.')
    w('')
    w('| Row | Statement | Citation | Relies on | Cited items | Status |')
    w('|---|---|---|---|---|---|')
    for r in rows:
        items = [s for s in r['source_items'].split('; ')]
        names = []
        for s in items:
            names.append(s.split(':', 1)[1] if ':' in s and '@' in s.split(':', 1)[0] else s)
        shown = ', '.join('`%s`' % n for n in names[:6]) + (' and %d more' % (len(names) - 6) if len(names) > 6 else '')
        w('| `%s` | %s | %s | %s | %s | %s |' % (
            r['id'], r['statement'].replace('|', '\\|'), r['proof_citation'].split(' (')[0],
            r['depends_on'].replace(',', ', ') or '-', shown.replace('|', '\\|'), r['static_status']))
    w('')
    open(out, 'w').write('\n'.join(L))


if __name__ == '__main__':
    main()
