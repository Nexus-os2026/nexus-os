#!/usr/bin/env python3
"""Render 01-MUTATION-EVIDENCE-MATRIX.md and 01-ACCEPTANCE-PROVENANCE.md from receipts/12-S1-LEDGER.json (read-only)."""
import json
import os
import sys

ROOT = sys.argv[1]
L = json.load(open(os.path.join(ROOT, "receipts/12-S1-LEDGER.json")))
ids = [k for k in L if not k.startswith("_")]
order = ["C1", "C2", "C3a", "C3b", "C3c", "C4", "C5", "C6", "C7", "C8", "C9", "C10", "C11", "C12", "C15", "C16", "C17",
         "C18a", "C18b", "C20", "C23", "C24", "C25", "C26", "C14", "C19", "C21", "C22", "C27", "C28", "A1", "A2", "A3",
         "A5", "A6"]
assert sorted(order) == sorted(ids), (sorted(order), sorted(ids))
s = lambda x, n=16: (str(x)[:n] + "…") if x and len(str(x)) > n else str(x or "—")

m = ["# Stage 1 — 35-control mutation evidence matrix",
     "",
     "Mission P3-C11-DR01-D2A1-FINAL-CLOSURE-01. Generated by `tools/render_s1.py` from `receipts/12-S1-LEDGER.json`,",
     "itself produced once by the frozen `tools/s1_mutations.py` (`receipts/10-STAGE1-TOOL-FREEZE.txt`; 647 of 647 checks",
     "hold, `01-CAMPAIGN-CHECKS.txt`). Every hash below was recomputed from Git objects at the evidence head",
     "`cca0d773d9a405be566e576886321acf6a28f29b` (an evidence-only descendant of Candidate C). Every mutant source blob",
     "was re-derived independently by applying the frozen catalog patch to Candidate C's file in a throw-away scratch",
     "copy. Pinned mutant executables still on disk were hashed, never run. **No mutation was applied to any worktree,",
     "built, run or rerun by this mission.** Full hashes are in `01-MUTATION-DECISIONS.tsv`.",
     "",
     "Labels: **[GIT]** read from a Git object; **[RAW]** recomputed from raw receipt bytes; **[ARCH]** an Architect",
     "decision, with the provenance of its record in `01-ACCEPTANCE-PROVENANCE.md`.",
     "",
     "| # | Control | Change (catalog) | Named property · configuration | Receipt type | First failure as printed [RAW] | Recording | Patch sha256 [GIT] | Mutant blob [RAW, re-derived] | Mutant exe sha256 [GIT; on disk] | Failing raw sha256 [RAW] | Restored side [GIT] | Restoration [GIT] | Decision [ARCH] |",
     "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for n, cid in enumerate(order, 1):
    x = L[cid]
    exe = x.get("mutant_exe_sha256")
    ond = x.get("mutant_exe_on_disk") or x.get("on_disk_mutant")
    exe_s = "NOT PRODUCED BY DESIGN" if exe == "NOT PRODUCED BY DESIGN" else \
        f"`{s(exe)}`; {'on disk, equal' if ond == exe else 'on disk: ' + s(ond, 24)}"
    dec = x.get("decision", "")
    dec_s = "ACCEPTED (by-ID Git record)" if dec.startswith("MUTATION CONTROL KILL ACCEPTED") else \
        "ACCEPTED (conversational ruling; no Git record)"
    m.append(f"| {n} | {cid} | {x.get('description')} | {x.get('named_property') or 'its named test'} · {x.get('configuration')} | "
             f"{x.get('receipt_type')} | {s(x.get('first_failure'), 60)} | {x.get('recording') or '—'} | "
             f"`{s(x.get('catalog_patch_sha256'))}` | `{s(x.get('mutant_blob'), 12)}` | {exe_s} | "
             f"`{s(x.get('primary_raw_sha256'))}` | {s(x.get('restored_side'), 70)} | {s(x.get('restoration'), 40)} | {dec_s} |")
m += ["",
      "## Witness-bound controls",
      "",
      "| Control | Primary (type (a)) first failure | Mutant witness (type (c)) positive line(s) [RAW] | Witness raw sha256 | Healthy witness (type (e3)) | Rule record |",
      "|---|---|---|---|---|---|"]
for cid in ("C1", "C25", "C4"):
    x = L[cid]
    note = ("recorded as printed under G.5(A); C4's attribution of both P4 and P8 comes only from the G.5(B) witness"
            if cid == "C4" else "recorded as printed under G.3(a); never counted as the named property")
    m.append(f"| {cid} | {x.get('first_failure')} ({note}) | "
             f"{'; '.join(x.get('witness_lines', []))} | `{s(x.get('witness_raw_sha256'))}` | {s(x.get('healthy_reference'), 90)} | "
             f"{'G.3' if cid != 'C4' else 'G.5 (A)-(D), (E) identity'}: holds = {x.get('g_rule_holds')} |")
c7 = L["C7"]
m += [f"| C7 | {c7.get('first_failure')} on the original F-PT explorer, A4 on, {c7.get('primary_states')} states ({c7.get('primary_verdict')}) | "
      f"{'; '.join(c7.get('witness_lines', []))} | `{s(c7.get('witness_raw_sha256'))}` | healthy witness {c7.get('healthy_verdict')}, raw `{s(c7.get('healthy_raw_sha256'))}` | "
      f"AD-C7-W G.7/G.9; Stage 12: {'; '.join(c7.get('final_classification', []))} |",
      "",
      "C7, recorded exactly: **C7: P6 (first failure E11; witness)**. The original F-PT explorer FAILed **E11**; no original",
      "F-PT P6 failure is claimed. The mutant witness printed E11 at the step-13 transition and P6 after step 24. The",
      "healthy witness PASSed. Restoration: EXACTLY_W. The restored-side baseline link is Candidate C only, under CR-B",
      f"({'; '.join(c7.get('link', []))}).",
      "",
      "## Receipts that were not the accepted ones (kept as history, never relabelled)",
      "",
      "| Control | Receipt | First line (unchanged) | Why it is not the accepted receipt |",
      "|---|---|---|---|"]
why = {"C5": "the run was stopped at the build gate; the accepted run (tranche 2 continuation) used this preserved build under the narrow C5 build-admissibility ruling",
       "C24": "the run was stopped at the build gate; the accepted run (tranche 3 continuation) used this preserved build under the narrow C24/C3b/C3c build-admissibility ruling",
       "C28": "the run was stopped at the build gate; the accepted run (tranche 1 continuation) used this preserved build under the narrow C28 build-admissibility ruling",
       "C7": "historical E-C-based C7 mutant: original F-PT FAIL E11; Architect ruled MUTATION_CONTROL_BLOCKED; superseded by the AD-C7-W route"}
for cid, lst in sorted(L["_superseded_receipts"].items()):
    for p, fl in lst:
        m.append(f"| {cid} | `{p}` | `{fl}` | {why.get(cid, '')} |")
m += ["",
      "## What this matrix does not do",
      "",
      "- It reruns, rebuilds or reapplies no control, and changes no receipt, label, patch or catalog entry.",
      "- An executor label (`KILL_EVIDENCE_CANDIDATE`, `MUTATION_CONTROL_BLOCKED`) is never an acceptance; acceptance is",
      "  only the Architect's ruling, whose record provenance is given in `01-ACCEPTANCE-PROVENANCE.md`.",
      "- No mutation is a production change: every mutant identity is Candidate C plus one frozen catalog patch, verified by",
      "  blob, and every mutant worktree was restored and verified by blob equality (EXACTLY_C, or EXACTLY_W for C7).",
      "- Every result is the explored model's, conditional on storage assumptions A-1 and A-2 (undischarged)."]
open(os.path.join(ROOT, "01-MUTATION-EVIDENCE-MATRIX.md"), "x").write("\n".join(m) + "\n")

p = ["# Stage 1 — acceptance provenance of the 35 decisions",
     "",
     "Generated by `tools/render_s1.py` from `receipts/12-S1-LEDGER.json`. **A string is never authority.** Each record",
     "below is executor-written audit evidence of a ruling that the Sole Architect conveyed in mission text. None carries a",
     "signature. A SHA256 authenticates the bytes of a record, not the truth of what it says.",
     "",
     "## The nine by-ID Git ruling records (33 controls)",
     "",
     "| # | Record (at evidence head `cca0d773`) | Git blob | sha256 | Count stated | Controls stated accepted | Recordings stated |",
     "|---|---|---|---|---|---|---|"]
for n, r in enumerate(L["_rulings"], 1):
    p.append(f"| {n} | `{r['path'].replace('docs/evidence/p3-candidate11/', '')}` | `{r['blob']}` | `{r['sha256']}` | "
             f"{r['count_stated'] or '—'} | {' '.join(r['accepted_stated'])} | {'; '.join(r['recordings']) or '—'} |")
union = sorted({c for r in L["_rulings"] for c in r["accepted_stated"]})
p += ["",
      f"Union of controls stated accepted: **{len(union)}** — {' '.join(union)}. C4 and C7 appear in no by-ID record. A4 appears",
      "in no kill list (it is SATISFIED — ARCHITECT ACCEPTED separately; it is not kill-required).",
      "",
      "Each cited `RESULT.txt` blob and sha256 in these records was matched against the Git object (checks in",
      "`01-CAMPAIGN-CHECKS.txt`). Three accepted runs (C28, C5, C24) used a preserved earlier build admitted by its own",
      "narrow build-admissibility ruling record:",
      ""]
for cid in ("C28", "C5", "C24"):
    a = L[cid].get("build_admission_ruling")
    p.append(f"- **{cid}:** build receipts in `{L[cid].get('build_receipt_dir')}`; admission record `{a[0]}` (blob `{a[1]}`), "
             f"title `{a[2]}`.")
p += ["",
      "## C4 and C7 — conversational rulings (no Git record)",
      "",
      "| Control | Ruling as conveyed | Recording | Provenance and its limits |",
      "|---|---|---|---|",
      f"| C4 | Architect accepted (stated in this mission's section 1: 'Previously Architect accepted. The governing conversational checkpoint records P4 and P8, first failure P4.') | `{L['C4']['recording']}` | {L['C4']['decision_provenance']}. The C4 receipt's own G.5 record says `E_architect_review: PENDING` (it was written before the ruling). **No separately signed or committed ruling record exists; none is invented.** |",
      f"| C7 | Architect accepted under P3-C11-DR01-D2A1-C7-ACCEPTANCE-01 (stated in this mission's section 1) | `{L['C7']['recording']}` | {L['C7']['decision_provenance']}. The published C7 packet (`cca0d773`) ends at the executor maximum `KILL_EVIDENCE_CANDIDATE — ARCHITECT REVIEW PENDING`. **No Git record of the acceptance exists; none is invented.** |",
      "",
      "Indirect Git corroboration for C4 (not an acceptance record): the executor-written AD-C7-W Owner adoption record",
      "(`d2a1-c7-adc7w-owner-adoption-01/OWNER-ADOPTION-2026-10-15.md`, blob `f9ce488c`) states 'Mutation campaign: 34/35",
      "ARCHITECT ACCEPTED' with 'C7: MUTATION_CONTROL_BLOCKED', and 'The 34 accepted controls stay frozen.'",
      "",
      "## Amendments applied per control",
      "",
      "| Control | Governing rules |",
      "|---|---|"]
for cid in order:
    p.append(f"| {cid} | {L[cid].get('amendment')} |")
p += ["",
      "## Result",
      "",
      "All 35 Architect decisions are linked to admissible accepted evidence: 33 through by-ID Git ruling records, and C4",
      "and C7 through conversational rulings conveyed in this mission's text, each accurately identified as such. No",
      "control's decision provenance is missing; the C4 and C7 records are conversational only (an Owner/Architect",
      "decision may choose to commit them; this mission does not)."]
open(os.path.join(ROOT, "01-ACCEPTANCE-PROVENANCE.md"), "x").write("\n".join(p) + "\n")
print("rendered")
